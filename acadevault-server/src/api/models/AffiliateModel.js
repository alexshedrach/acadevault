import mongoose from "mongoose";

// Schema setup
const { Schema, model } = mongoose;
const { ObjectId } = Schema;

// Affiliate Schema Definition
const AffiliateSchema = new Schema(
  {
    userId: {
      type: ObjectId,
      ref: "User",
      required: true,
      unique: true,
    }, // Reference to the user acting as an affiliate
    balance: {
      type: Number,
      default: 0,
      min: 0,
    }, // Current balance available for withdrawal
    code: {
      type: String,
      unique: true,
      required: [true, "An affiliate code is required."],
      match: [/^AFF-[A-Z0-9]{8}$/, "Invalid affiliate code format."], // Enforced format for affiliate codes
    },
    commissionRate: {
      type: Number,
      required: [true, "Commission rate is required."],
      min: [0, "Commission rate cannot be negative."],
      max: [100, "Commission rate cannot exceed 100%."],
    }, // Percentage commission rate for transactions
    totalReferrals: {
      type: Number,
      default: 0,
      min: 0,
    }, // Total number of successful referrals
    isActive: {
      type: Boolean,
      default: true,
    }, // Indicates if the affiliate is currently active
    transactions: [
      {
        type: ObjectId,
        ref: "Transaction",
      },
    ], // Transactions linked to the affiliate
    totalEarnings: {
      type: Number,
      default: 0,
      min: 0,
    }, // Total earnings generated by the affiliate
    affiliateTier: {
      type: String,
      enum: ["basic", "silver", "gold", "platinum"], // Tier of the affiliate based on performance
      default: "basic",
    },
    performanceMetrics: {
      clicks: {
        type: Number,
        default: 0,
        min: 0,
      }, // Number of clicks generated by the affiliate's links
      conversions: {
        type: Number,
        default: 0,
        min: 0,
      }, // Number of conversions from the affiliate's referrals
    },
    createdAt: {
      type: Date,
      default: Date.now,
    }, // Date the affiliate account was created
  },
  {
    timestamps: true,
    toJSON: { virtuals: true },
    toObject: { virtuals: true },
  }
);

// === Indexing ===
AffiliateSchema.index({ userId: 1, code: 1 }, { unique: true });
AffiliateSchema.index({ isActive: 1 });
AffiliateSchema.index({ affiliateTier: 1 });



/// === Export Model === ///
const Affiliate = model("Affiliate", AffiliateSchema);
export default Affiliate;
